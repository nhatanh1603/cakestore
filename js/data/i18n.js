export function registerProductsI18n(products) {
    if (!Array.isArray(products)) return;
    products.forEach(p => {
        if (p.id) {
            if (!I18N.vi[p.id]) I18N.vi[p.id] = p.name_vi;
            if (!I18N.en[p.id]) I18N.en[p.id] = p.name_en;
        }
    });
}

export function getLanguage() {
    return localStorage.getItem("poeme_lang") || "en";
}

export function setLanguage(lang) {
    if (!I18N[lang]) lang = 'en';
    localStorage.setItem('poeme_lang', lang);

    const langSwitches = document.querySelectorAll('.lang-switch');
    langSwitches.forEach(sw => {
        sw.classList.toggle('is-vi', lang === 'vi');
    });

    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (I18N[lang] && I18N[lang][key]) {
            const val = I18N[lang][key];
            if (val.includes('<') && val.includes('>')) {
                el.innerHTML = val;
            } else {
                el.textContent = val;
            }
        }
    });

    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
        const key = el.getAttribute('data-i18n-ph');
        if (I18N[lang] && I18N[lang][key]) {
            el.setAttribute('placeholder', I18N[lang][key]);
        }
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (I18N[lang] && I18N[lang][key]) {
            el.setAttribute('title', I18N[lang][key]);
        }
    });
}

if (typeof window !== "undefined") {
    window.I18N = I18N;
    window.setLanguage = setLanguage;
    window.getLanguage = getLanguage;
    window.registerProductsI18n = registerProductsI18n;
}
